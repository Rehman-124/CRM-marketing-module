import { Fragment, useEffect, useMemo, useRef, useState } from 'react'
import { Link, useNavigate, useParams } from 'react-router-dom'
import { ArrowLeft, Inbox as InboxIcon, Search, PanelRightOpen, PlugZap, MessageSquareDashed, ShieldOff, AlertCircle, Radio, WifiOff, Loader2, FlaskConical } from 'lucide-react'
import { Badge, Button, EmptyState, Input, Segmented, Select, cn } from '@/components/ui'
import { Drawer } from '@/components/ui/overlay'
import { CompanyTag, ReadOnlyBadge } from '@/components/domain'
import { DaySeparator, MessageBubble, ModeBadge, PlatformBadge, PlatformIcon, sameDay } from '@/components/inbox/parts'
import { Composer } from '@/components/inbox/Composer'
import { ClientPanel } from '@/components/inbox/ClientPanel'
import { toast } from '@/components/ui/overlay'
import { useAppData, useMe, useRun } from '@/store/store'
import { useScope } from '@/store/hooks'
import { canViewEnquiry } from '@/domain/permissions'
import { canReply, discardFailed, hasFailedSend, lastMessage, threadNow } from '@/domain/messaging'
import { companyName, userName } from '@/domain/engine'
import { CONNECTION_LABEL, ENQUIRY_CHANNELS, SOURCE_LABEL } from '@/domain/constants'
import { isLive, retryReply, simulateClientReply, useMessagingRuntime } from '@/messaging/service'
import { fmtRelative, fmtDateTime } from '@/lib/time'
import type { Enquiry, EnquiryChannel } from '@/domain/types'

type View = 'open' | 'unread' | 'converted' | 'all'

function modeReason(e: Enquiry, live: boolean, backend: string): string {
  if (e.origin === 'simulated') return 'This conversation was generated by the prototype. Replies are simulated and never reach Meta.'
  if (live) return 'Replies are sent to the client through Meta.'
  if (backend !== 'online') return 'The messaging server is unreachable. Replies will fail until it is back.'
  return 'No Meta credentials are configured on the server for this company and channel.'
}

function ServerChip() {
  const rt = useMessagingRuntime()
  if (rt.backend === 'checking') return <Badge tone="neutral" icon={Loader2}>Checking server…</Badge>
  if (rt.backend === 'offline') return <span title="No messaging server is reachable, so only simulated conversations can be used." className="inline-flex items-center gap-1 rounded-md bg-slate-100 px-1.5 py-0.5 text-[11px] font-medium text-slate-600 ring-1 ring-slate-200 ring-inset"><WifiOff className="size-3" />Server offline · simulated</span>
  const live = rt.status?.channels.filter((c) => c.live).length ?? 0
  return <span title={`${live} company channels have live credentials`} className="inline-flex items-center gap-1 rounded-md bg-emerald-50 px-1.5 py-0.5 text-[11px] font-medium text-emerald-700 ring-1 ring-emerald-200 ring-inset"><Radio className="size-3" />Server connected · {live} live</span>
}

export default function InboxPage() {
  const { id } = useParams()
  const S = useAppData()
  const me = useMe()
  const run = useRun()
  const navigate = useNavigate()
  const rt = useMessagingRuntime()
  const { companies, viewOnly } = useScope()
  const [view, setView] = useState<View>('open')
  const [channel, setChannel] = useState<EnquiryChannel | 'all'>('all')
  const [q, setQ] = useState('')
  const [details, setDetails] = useState(false)
  const scroller = useRef<HTMLDivElement>(null)

  const scoped = useMemo(() => S.enquiries.filter((e) => companies.includes(e.companyId)), [S.enquiries, companies])
  const counts = {
    open: scoped.filter((e) => e.status === 'open').length,
    unread: scoped.filter((e) => !e.read).length,
    converted: scoped.filter((e) => e.status === 'converted').length,
    all: scoped.length,
  }
  const rows = scoped
    .filter((e) => view === 'all' || (view === 'open' ? e.status === 'open' : view === 'unread' ? !e.read : e.status === 'converted'))
    .filter((e) => channel === 'all' || e.channel === channel)
    .filter((e) => !q || `${e.handle} ${e.fields.fullName} ${e.messages.map((m) => m.text).join(' ')} ${e.ref}`.toLowerCase().includes(q.toLowerCase()))
    .sort((a, b) => b.lastActivityAt - a.lastActivityAt)
    .slice(0, 200)

  const selected = id ? S.enquiries.find((x) => x.id === id) : undefined
  const allowed = selected ? canViewEnquiry(S, me, selected) : false
  const errors = S.connections.filter((c) => c.kind === 'meta_inbox' && companies.includes(c.companyId) && c.state === 'error')

  // Opening a conversation marks it read for people who can act on it
  useEffect(() => {
    if (selected && allowed && canReply(me, selected) && !selected.read) run((d) => { const x = d.enquiries.find((y) => y.id === selected.id); if (x) x.read = true })
  }, [selected?.id, selected?.read]) // eslint-disable-line react-hooks/exhaustive-deps
  // Keep the newest message in view
  useEffect(() => {
    const el = scroller.current
    if (el) el.scrollTop = el.scrollHeight
  }, [selected?.id, selected?.messages.length, selected?.messages.at(-1)?.status])

  // rt is subscribed above so this re-evaluates when the server status changes
  const live = selected ? isLive(selected) : false
  const thread = selected && allowed ? selected : null
  const connErr = !!thread && S.connections.some((c) => c.companyId === thread.companyId && c.kind === 'meta_inbox' && c.state === 'error')
  const panel = thread && <ClientPanel e={thread} live={live} checking={rt.backend === 'checking' && thread.origin === 'live'} reason={modeReason(thread, live, rt.backend)} />

  return (
    <div className="-mx-4 -my-6 flex h-[calc(100dvh-4rem)] overflow-hidden bg-white sm:-mx-6 lg:-mx-8 lg:-my-8">
      {/* ---------------- conversation list */}
      <aside aria-label="Conversations" className={cn('flex w-full shrink-0 flex-col border-r border-slate-200 md:w-[320px] lg:w-[340px]', id && 'hidden md:flex')}>
        <div className="border-b border-slate-100 px-4 pt-4 pb-3">
          <div className="flex items-center justify-between gap-2">
            <h1 className="text-[17px] font-semibold tracking-tight text-slate-900">Marketing Inbox</h1>
            <ServerChip />
          </div>
          <p className="mt-0.5 text-[12px] text-slate-500">Messenger, Instagram Direct and comments · P1-FR-001</p>
          <div className="mt-3"><Segmented size="sm" value={view} onChange={setView} options={[
            { value: 'open', label: 'Open', count: counts.open },
            { value: 'unread', label: 'Unread', count: counts.unread },
            { value: 'converted', label: 'Converted', count: counts.converted },
            { value: 'all', label: 'All', count: counts.all },
          ]} /></div>
          <div className="mt-2 flex gap-2">
            <div className="relative min-w-0 flex-1">
              <Search className="pointer-events-none absolute top-1/2 left-2.5 size-4 -translate-y-1/2 text-slate-400" />
              <Input value={q} onChange={(e) => setQ(e.target.value)} placeholder="Search" aria-label="Search conversations" className="h-8 pl-8 text-[12.5px]" />
            </div>
            <Select value={channel} onChange={(e) => setChannel(e.target.value as EnquiryChannel | 'all')} className="h-8 w-[118px] text-[12.5px]" aria-label="Channel">
              <option value="all">All channels</option>
              {ENQUIRY_CHANNELS.map((c) => <option key={c} value={c}>{SOURCE_LABEL[c]}</option>)}
            </Select>
          </div>
        </div>
        {errors.map((c) => (
          <div key={c.id} role="alert" className="flex items-start gap-2 border-b border-rose-100 bg-rose-50 px-4 py-2 text-[12px] text-rose-800">
            <PlugZap className="mt-0.5 size-3.5 shrink-0" />
            <span><b>{companyName(S, c.companyId)}</b> · {CONNECTION_LABEL[c.kind]} connection error. New messages are flagged, not lost.{me.role === 'admin' && <> <Link to="/integrations" className="font-semibold underline">Details</Link></>}</span>
          </div>
        ))}
        <div className="scroll-thin min-h-0 flex-1 overflow-y-auto">
          {rows.length === 0 ? (
            <EmptyState compact icon={InboxIcon} title={view === 'unread' ? 'No unread conversations' : view === 'open' ? 'Inbox zero' : 'No conversations'} description={view === 'open' || view === 'unread' ? 'New Facebook and Instagram messages and comments will appear here.' : 'Nothing matches the current filters.'} />
          ) : (
            <ul>
              {rows.map((e) => {
                const last = lastMessage(e)
                const failed = hasFailedSend(e)
                return (
                  <li key={e.id}>
                    <button
                      onClick={() => navigate(`/inbox/${e.id}`)}
                      aria-current={e.id === id ? 'true' : undefined}
                      className={cn('flex w-full items-start gap-3 border-b border-slate-100 px-4 py-3 text-left transition', e.id === id ? 'bg-brand-50/70' : 'hover:bg-slate-50')}
                    >
                      <span className="relative"><PlatformIcon e={e} />{!e.read && <span className="absolute -top-0.5 -right-0.5 size-2.5 rounded-full bg-brand-500 ring-2 ring-white" aria-label="Unread" />}</span>
                      <span className="min-w-0 flex-1">
                        <span className="flex items-baseline justify-between gap-2">
                          <span className={cn('truncate text-[13px]', !e.read ? 'font-semibold text-slate-900' : 'font-medium text-slate-800')}>{e.fields.fullName || e.handle}</span>
                          <span className="shrink-0 text-[11px] text-slate-500" title={fmtDateTime(e.lastActivityAt)}>{fmtRelative(e.lastActivityAt, threadNow(S, e))}</span>
                        </span>
                        <span className={cn('mt-0.5 block truncate text-[12.5px]', !e.read ? 'text-slate-700' : 'text-slate-500')}>
                          {last.from === 'marketing' ? (last.kind === 'public-reply' ? 'Public reply: ' : 'You: ') : ''}{last.text}
                        </span>
                        <span className="mt-1.5 flex flex-wrap items-center gap-1.5">
                          <CompanyTag id={e.companyId} className="text-[11.5px]" />
                          {e.status === 'converted' && <Badge tone="green">Converted</Badge>}
                          {failed && <Badge tone="red" icon={AlertCircle}>Not sent</Badge>}
                          {viewOnly(e.companyId) && <ReadOnlyBadge />}
                        </span>
                      </span>
                    </button>
                  </li>
                )
              })}
            </ul>
          )}
        </div>
      </aside>

      {/* ---------------- thread */}
      <section aria-label="Conversation" className={cn('flex min-w-0 flex-1 flex-col bg-slate-50/60', !id && 'hidden md:flex')}>
        {!id ? (
          <div className="flex flex-1 items-center justify-center"><EmptyState icon={MessageSquareDashed} title="Select a conversation" description="Choose a conversation on the left to read the messages and reply." /></div>
        ) : !selected ? (
          <div className="flex flex-1 items-center justify-center"><EmptyState icon={MessageSquareDashed} title="Conversation not found" action={<Link to="/inbox"><Button size="sm">Back to inbox</Button></Link>} /></div>
        ) : !allowed ? (
          <div className="flex flex-1 items-center justify-center"><EmptyState icon={ShieldOff} title="You don’t have access to this conversation" description="Access is scoped by role and company (P3-FR-001)." action={<Link to="/inbox"><Button size="sm">Back to inbox</Button></Link>} /></div>
        ) : thread && (
          <>
            <header className="flex items-center gap-3 border-b border-slate-200 bg-white px-3 py-2.5 sm:px-4">
              <Link to="/inbox" className="-ml-1 rounded-lg p-1.5 text-slate-500 hover:bg-slate-100 md:hidden" aria-label="Back to conversations"><ArrowLeft className="size-5" /></Link>
              <PlatformIcon e={thread} />
              <div className="min-w-0 flex-1">
                <p className="flex min-w-0 items-baseline gap-2">
                  <span className="truncate text-[14px] font-semibold text-slate-900">{thread.fields.fullName || thread.handle}</span>
                  <span className="hidden shrink-0 font-mono text-[11px] text-slate-500 sm:inline">{thread.ref}</span>
                </p>
                <p className="mt-0.5 flex flex-wrap items-center gap-x-2 gap-y-1 text-[12px] text-slate-500">
                  <PlatformBadge e={thread} />
                  <CompanyTag id={thread.companyId} className="text-[12px]" />
                  <span className="hidden sm:inline-flex"><ModeBadge live={live} checking={rt.backend === 'checking' && thread.origin === 'live'} /></span>
                </p>
              </div>
              {thread.origin === 'simulated' && (
                <Button size="xs" variant="ghost" icon={FlaskConical} onClick={() => simulateClientReply(thread.id)} title="Demo only: the client sends a message" aria-label="Simulate client message">
                  <span className="hidden 2xl:inline">Simulate client message</span>
                </Button>
              )}
              <Button size="xs" variant="secondary" icon={PanelRightOpen} onClick={() => setDetails(true)} className="xl:hidden" aria-label="Client details"><span className="hidden sm:inline">Details</span></Button>
            </header>
            {thread.postContext && <div className="border-b border-slate-200 bg-white px-4 py-2 text-[12px] text-slate-500">{thread.postContext}</div>}
            <div ref={scroller} className="scroll-thin min-h-0 flex-1 overflow-y-auto px-3 py-4 sm:px-6" role="log" aria-live="polite" aria-label={`Messages with ${thread.handle}`} tabIndex={0}>
              <div className="mx-auto max-w-3xl space-y-3">
                {thread.messages.map((m, i) => (
                  <Fragment key={m.id}>
                    {(i === 0 || !sameDay(thread.messages[i - 1].at, m.at)) && <DaySeparator t={m.at} />}
                    <MessageBubble
                      m={m} e={thread} canAct={canReply(me, thread)}
                      author={m.via === 'meta' ? 'Meta Business Suite' : userName(S, m.byUserId)}
                      onRetry={async () => { const r = await retryReply(thread.id, m.id, me); if (!r.ok) toast.error('Can’t retry', r.error) }}
                      onDiscard={() => run((d) => discardFailed(d, thread.id, m.id))}
                    />
                  </Fragment>
                ))}
              </div>
            </div>
            {canReply(me, thread) ? (
              <Composer e={thread} me={me} now={threadNow(S, thread)} live={live} connectionError={connErr} />
            ) : (
              <p className="flex items-center gap-2 border-t border-slate-200 bg-white px-4 py-3.5 text-[12.5px] text-slate-500">
                <ShieldOff className="size-4" />{viewOnly(thread.companyId) ? 'This company is view-only for you — you can read but not reply.' : 'Replies are sent by Marketing employees for their companies and by the Admin / CRM Manager.'}
              </p>
            )}
          </>
        )}
      </section>

      {/* ---------------- client details */}
      {thread && <aside aria-label="Client details" tabIndex={0} className="scroll-thin hidden w-[340px] shrink-0 overflow-y-auto border-l border-slate-200 bg-white xl:block">{panel}</aside>}
      {thread && <Drawer open={details} onClose={() => setDetails(false)} title="Client details" description={thread.ref}>{panel}</Drawer>}
    </div>
  )
}
