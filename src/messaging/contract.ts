// Messaging contract shared by the CRM frontend and the Node messaging server (server/).
// Erasable TypeScript only (no enums), so Node can run it directly.

export type CompanyKey = 'flightnest' | 'holidaynest' | 'trip2go' | 'travelope' | 'schengentravel' | 'trip2goglobal'

/** Meta messaging surfaces supported by this integration. */
export type MessagingChannel = 'messenger' | 'instagram'

/** dm = reply in a direct-message thread; private-reply = one private message to a commenter; public-reply = reply posted under the comment. */
export type SendKind = 'dm' | 'private-reply' | 'public-reply'

export type MessagingErrorCode =
  | 'outside_window' // Meta's 24-hour standard messaging window has closed
  | 'private_reply_used' // a comment can receive only one private reply
  | 'rate_limited'
  | 'token_invalid' // access token expired or revoked
  | 'permission_missing' // app/page lacks the permission (or App Review) for this action
  | 'recipient_unavailable'
  | 'invalid_request'
  | 'not_configured' // no credentials for this company/channel on the server
  | 'forbidden' // CRM user may not reply for this company
  | 'network'
  | 'unknown'

export interface MessagingError {
  code: MessagingErrorCode
  message: string
  retryable: boolean
  retryAfterSec?: number
}

export interface SendRequest {
  /** Generated by the CRM; the server uses it to make retries idempotent. */
  clientMessageId: string
  companyId: CompanyKey
  channel: MessagingChannel
  kind: SendKind
  /** PSID (Messenger) or IGSID (Instagram) — required for dm */
  recipientId?: string
  /** Comment id — required for private-reply and public-reply */
  commentId?: string
  text: string
}

export type SendResult =
  | { ok: true; externalId: string; acceptedAt: number; /** Private replies: the commenter's messaging id returned by Meta */ recipientId?: string }
  | { ok: false; error: MessagingError }

/** Normalised events the server pushes to the CRM (from Meta webhooks). */
export type InboundEvent =
  | { type: 'message'; companyId: CompanyKey; channel: MessagingChannel; senderId: string; text: string; externalId: string; at: number; echo: boolean; recipientId?: string; senderName?: string }
  | { type: 'comment'; companyId: CompanyKey; channel: MessagingChannel; commentId: string; senderId: string; senderName: string; text: string; at: number; postId?: string }
  | { type: 'delivery'; companyId: CompanyKey; channel: MessagingChannel; senderId: string; externalIds: string[]; watermark: number }
  | { type: 'read'; companyId: CompanyKey; channel: MessagingChannel; senderId: string; watermark: number }

export interface ChannelStatus {
  companyId: CompanyKey
  channel: MessagingChannel
  /** True only when credentials for this company/channel are configured on the server. */
  live: boolean
  missing: string[]
}

export interface StatusResponse {
  server: 'ok'
  graphVersion: string
  webhookConfigured: boolean
  channels: ChannelStatus[]
}

