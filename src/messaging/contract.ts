/** Who may send replies: Marketing employees for their assigned companies, and Admin / CRM Manager (product-owner decision, 18 Oct 2026). */
export function mayReply(user: { role: string; companyIds: string[] }, companyId: string): boolean {
  if (user.role === 'admin') return true
  return user.role === 'marketing' && user.companyIds.includes(companyId)
}
